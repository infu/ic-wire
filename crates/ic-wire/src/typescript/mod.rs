/// Explicit browser payload allowances, owned by the consuming application.
///
/// Node/depth accounting follows the selected browser runtime, not Rust Serde
/// traversal. No native allocation allowance is translated into a JS heap limit.
#[derive(Clone, Copy, Debug)]
pub struct PayloadLimits {
    /// Maximum payload bytes, excluding any frame or transport envelope.
    /// A message requires at least one byte for its sparse root.
    pub bytes: u64,
    /// Maximum runtime value visits; must be nonzero.
    pub nodes: u64,
    /// Maximum runtime value depth; must be nonzero.
    pub depth: u64,
}

/// One typed request/response contract for generated framed clients.
///
/// Both byte allowances are payload-only; generation adds the existing 11-byte
/// header. Node/depth allowances retain browser runtime accounting.
#[derive(Clone, Copy, Debug)]
pub struct Method<'a> {
    /// Exported codec identifier. Does not implicitly determine the method ID.
    pub export: &'a str,
    /// Exact routing identity; use crate::method_id explicitly for named IDs.
    pub id: u64,
    /// Admitted request type name.
    pub request: &'a str,
    /// Admitted response type name.
    pub response: &'a str,
    /// Request payload allowances.
    pub request_limits: PayloadLimits,
    /// Response payload allowances.
    pub response_limits: PayloadLimits,
}

/// One mounted endpoint and its existing TypeScript method codec.
#[cfg(feature = "service-client")]
#[derive(Clone, Copy, Debug)]
pub struct ServiceMethod<'a> {
    /// Public property name on the generated service client.
    pub binding: &'a str,
    /// Identifier imported from the method's codec module.
    pub codec_export: &'a str,
    /// Deployed name passed verbatim to the transport.
    pub endpoint: &'a str,
    /// Module specifier exporting the codec generated by `method_module`.
    pub codec_module: &'a str,
    /// Mounted call mode: `query`, `composite_query` or `update`.
    pub mode: &'a str,
}

/// Invalid metadata or exhausted schema generation allowance.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum GenerationError {
    /// Unsupported shape, invalid field, unresolved name or alias-only cycle.
    Schema,
    /// Metadata or output exceeds its schema allowance.
    Complexity,
}

/// Schema limits, independent of codec runtime allowances.
#[derive(Clone, Copy, Debug)]
pub struct SchemaLimits {
    /// Maximum number of named definitions plus inline nodes.
    pub nodes: usize,
    /// Maximum nested inline JSON depth; references are not expanded.
    pub depth: usize,
    /// Maximum total bytes of names, field/variant labels and check names retained.
    pub names_bytes: usize,
    /// Maximum bytes per emitted declaration or metadata artifact.
    pub output_bytes: usize,
}

impl Default for SchemaLimits {
    fn default() -> Self {
        Self {
            nodes: 65_536,
            depth: 64,
            names_bytes: 1_048_576,
            output_bytes: 1_048_576,
        }
    }
}

#[derive(Debug)]
struct ScalarBounds {
    min: Option<Number>,
    max: Option<Number>,
}

#[derive(Debug)]
struct Annotations {
    check: Option<String>,
    bounds: Option<ScalarBounds>,
    fixed: bool,
    projected: bool,
}

#[derive(Debug)]
struct ExtensionField {
    id: u32,
    name: String,
    child: usize,
    required: bool,
}

#[derive(Debug)]
enum Node {
    Unit,
    Bool,
    Integer {
        bits: u8,
        signed: bool,
    },
    Float {
        bits: u8,
    },
    Text {
        max: Option<u64>,
    },
    Bytes {
        min: Option<u64>,
        max: Option<u64>,
    },
    Packed {
        word: &'static str,
        nonzero: bool,
        max: Option<u64>,
    },
    List {
        item: usize,
        max: Option<u64>,
    },
    Array {
        item: usize,
        len: u64,
    },
    Tuple(Vec<usize>),
    Result {
        ok: usize,
        err: usize,
    },
    Option(usize),
    Recover(usize),
    Alias(usize),
    Ref(usize),
    Record(Vec<(String, usize)>),
    Enum(Vec<(String, u32, usize)>),
    ExtensionRecord {
        fields: Vec<(String, usize)>,
        extensions: Vec<ExtensionField>,
    },
    ExtensionTuple {
        items: Vec<usize>,
        extensions: Vec<ExtensionField>,
    },
    OpenVariant {
        variants: Vec<(String, u32, usize)>,
        required: bool,
    },
}

/// Immutable admitted registry with private node indices.
///
/// Supplied definition names are preserved.
/// Input metadata can be mutated or dropped after construction without changing
/// the graph. All rendering consumes this graph, never the original JSON.
#[derive(Debug)]
pub struct ValidatedRegistry {
    names: Vec<String>,
    roots: Vec<usize>,
    nodes: Vec<Node>,
    annotations: BTreeMap<usize, Annotations>,
    output_bytes: usize,
}

impl ValidatedRegistry {
    /// Import explicit definitions in the Wire metadata grammar.
    ///
    /// Supported kinds: unit, bool, u/i, float, text, bytes, packed, list,
    /// array, tuple, result, option, recover, newtype, ref, record, enum,
    /// extension-record, extension-tuple and open-variant. Unknown keys reject;
    /// manual metadata must match the consumer's actual Serde representation.
    /// Records and tuples may declare `"fixed":true` for typed method admission.
    /// `"projected":true` identifies a generated extension layout that the
    /// typed Rust codec projects recursively.
    ///
    /// # Errors
    /// Returns Schema for invalid metadata and Complexity for exceeded bounds.
    /// Failure returns no partially usable registry. Input JSON allocation is
    /// caller-owned; limits apply to graph import, not parsing external JSON text.
    pub fn from_metadata(
        types: &BTreeMap<String, Value>,
        limits: SchemaLimits,
    ) -> Result<Self, GenerationError> {
        if limits.depth > 64 || types.len() > limits.nodes {
            return Err(GenerationError::Complexity);
        }
        let mut importer = Importer {
            nodes: Vec::new(),
            annotations: BTreeMap::new(),
            names: BTreeMap::new(),
            remaining: limits.nodes - types.len(),
            name_bytes: limits.names_bytes,
            depth: limits.depth,
        };
        let mut names = Vec::new();
        for (index, name) in types.keys().enumerate() {
            identifier(name)?;
            let name = importer.name(name)?;
            importer.names.insert(name.clone(), index);
            names.push(name);
        }
        let mut roots = Vec::new();
        for value in types.values() {
            roots.push(importer.parse(value, 0)?);
        }
        let graph = Self {
            names,
            roots,
            nodes: importer.nodes,
            annotations: importer.annotations,
            output_bytes: limits.output_bytes,
        };
        graph.validate_aliases()?;
        Ok(graph)
    }

    fn evolving_root_nodes(&self, roots: &[usize]) -> Result<Vec<usize>, GenerationError> {
        if roots.is_empty() {
            return Ok(Vec::new());
        }
        let mut checked_roots = vec![false; self.nodes.len()];
        let mut evolving = Vec::new();
        for &root in roots {
            let mut id = self.roots[root];
            // Alias cycles have already been rejected. Share the walk across roots.
            while !core::mem::replace(&mut checked_roots[id], true) {
                match &self.nodes[id] {
                    Node::Alias(item) => id = *item,
                    Node::Ref(root) => id = self.roots[*root],
                    Node::ExtensionRecord { .. } | Node::ExtensionTuple { .. } => {
                        evolving.push(id);
                        break;
                    }
                    _ => return Err(GenerationError::Schema),
                }
            }
        }
        Ok(evolving)
    }

    fn validate_evolving_roots(&self, roots: &BTreeSet<String>) -> Result<(), GenerationError> {
        let indices = roots
            .iter()
            .map(|root| self.root_index(root))
            .collect::<Result<Vec<_>, _>>()?;
        self.validate_projection_layouts(self.evolving_root_nodes(&indices)?.into_iter())
    }

    fn validate_message_roots(&self, roots: &[usize]) -> Result<(), GenerationError> {
        let roots = self.evolving_root_nodes(roots)?;
        // A projected root declares that its descendants follow Rust's
        // generated projection. Manually supplied layouts own their encoding.
        self.validate_projection_layouts(
            roots
                .into_iter()
                .filter(|id| self.annotations.get(id).is_some_and(|a| a.projected)),
        )
    }

    fn validate_projection_layouts(
        &self,
        roots: impl Iterator<Item = usize>,
    ) -> Result<(), GenerationError> {
        let mut pending = Vec::new();
        for id in roots {
            match &self.nodes[id] {
                Node::ExtensionRecord { fields, extensions } => {
                    pending.extend(fields.iter().map(|(_, child)| (*child, true)));
                    pending.extend(extensions.iter().map(|entry| (entry.child, true)));
                }
                Node::ExtensionTuple { items, extensions } => {
                    pending.extend(items.iter().map(|&item| (item, true)));
                    pending.extend(extensions.iter().map(|entry| (entry.child, true)));
                }
                _ => unreachable!("admitted evolving root"),
            }
        }
        if pending.is_empty() {
            return Ok(());
        }

        // Generated projection follows containers. A fixed Serde aggregate
        // decodes its descendants as ordinary Serde, so reachability from each
        // context must be checked separately even for the same named node.
        let mut visited = vec![[false; 2]; self.nodes.len()];
        while let Some((id, can_project)) = pending.pop() {
            if core::mem::replace(&mut visited[id][usize::from(can_project)], true) {
                continue;
            }
            let flags = self.annotations.get(&id);
            let fixed = !can_project || flags.is_some_and(|a| a.fixed);
            let projected = can_project && flags.is_some_and(|a| a.projected);
            match &self.nodes[id] {
                Node::Record(fields) if fixed => {
                    pending.extend(fields.iter().map(|(_, child)| (*child, false)));
                }
                Node::Tuple(items) if fixed => {
                    pending.extend(items.iter().map(|&item| (item, false)));
                }
                Node::ExtensionRecord { fields, extensions } if projected => {
                    pending.extend(fields.iter().map(|(_, child)| (*child, true)));
                    pending.extend(extensions.iter().map(|entry| (entry.child, true)));
                }
                Node::ExtensionTuple { items, extensions } if projected => {
                    pending.extend(items.iter().map(|&item| (item, true)));
                    pending.extend(extensions.iter().map(|entry| (entry.child, true)));
                }
                Node::List { item, .. } | Node::Array { item, .. } | Node::Option(item) => {
                    pending.push((*item, can_project))
                }
                Node::Alias(item) => pending.push((*item, false)),
                Node::Ref(root) => pending.push((self.roots[*root], can_project)),
                Node::Result { ok, err } => {
                    pending.extend([(*ok, can_project), (*err, can_project)]);
                }
                Node::Enum(variants) => {
                    pending.extend(variants.iter().map(|(_, _, child)| (*child, false)));
                }
                Node::Record(_)
                | Node::Tuple(_)
                | Node::ExtensionRecord { .. }
                | Node::ExtensionTuple { .. }
                | Node::OpenVariant { .. }
                | Node::Recover(_) => return Err(GenerationError::Schema),
                Node::Unit
                | Node::Bool
                | Node::Integer { .. }
                | Node::Float { .. }
                | Node::Text { .. }
                | Node::Bytes { .. }
                | Node::Packed { .. } => {}
            }
        }
        Ok(())
    }

    // Linear worklist over transparent edges. Productive recursive records,
    // lists and options terminate an alias chain rather than expanding it.
    fn validate_aliases(&self) -> Result<(), GenerationError> {
        let mut state = vec![0_u8; self.nodes.len()];
        let mut path = Vec::new();
        for start in 0..self.nodes.len() {
            let mut current = start;
            path.clear();
            loop {
                match state[current] {
                    1 => return Err(GenerationError::Schema),
                    2 => break,
                    _ => {}
                }
                state[current] = 1;
                path.push(current);
                match self.nodes[current] {
                    Node::Alias(next) => current = next,
                    Node::Ref(root) => current = self.roots[root],
                    _ => break,
                }
            }
            for node in &path {
                state[*node] = 2;
            }
        }
        Ok(())
    }
}

struct Importer {
    nodes: Vec<Node>,
    annotations: BTreeMap<usize, Annotations>,
    names: BTreeMap<String, usize>,
    remaining: usize,
    name_bytes: usize,
    depth: usize,
}

impl Importer {
    fn name(&mut self, name: &str) -> Result<String, GenerationError> {
        self.name_bytes = self
            .name_bytes
            .checked_sub(name.len())
            .ok_or(GenerationError::Complexity)?;
        Ok(name.to_string())
    }

    fn parse_extensions<'a>(
        &mut self,
        value: &'a Value,
        depth: usize,
        names: &mut BTreeSet<&'a str>,
        tuple_core_slots: Option<u32>,
    ) -> Result<Vec<ExtensionField>, GenerationError> {
        let entries = value.as_array().ok_or(GenerationError::Schema)?;
        if entries.len() > self.remaining {
            return Err(GenerationError::Complexity);
        }
        let mut extensions = Vec::new();
        let mut previous = tuple_core_slots.unwrap_or(0);
        for entry in entries {
            keys(entry, &["name", "id", "value", "required"])?;
            let name = text(entry, "name")?;
            let id = entry["id"]
                .as_u64()
                .and_then(|n| u32::try_from(n).ok())
                .ok_or(GenerationError::Schema)?;
            let required = entry["required"].as_bool().ok_or(GenerationError::Schema)?;
            if id <= previous
                || (tuple_core_slots.is_some() && (required || previous.checked_add(1) != Some(id)))
                || !names.insert(name)
            {
                return Err(GenerationError::Schema);
            }
            previous = id;
            extensions.push(ExtensionField {
                id,
                name: self.name(name)?,
                child: self.parse(&entry["value"], depth + 1)?,
                required,
            });
        }

        Ok(extensions)
    }

    fn parse(&mut self, value: &Value, depth: usize) -> Result<usize, GenerationError> {
        if depth > self.depth {
            return Err(GenerationError::Complexity);
        }
        self.remaining = self
            .remaining
            .checked_sub(1)
            .ok_or(GenerationError::Complexity)?;
        let kind = text(value, "k")?;
        let allowed: &[&str] = match kind {
            "unit" | "bool" => &["k", "check"],
            "u" | "i" | "float" => &["k", "check", "bits", "min", "max"],
            "text" => &["k", "check", "max"],
            "packed" => &["k", "check", "word", "nonzero", "max"],
            "bytes" => &["k", "check", "min", "max"],
            "list" | "array" => &["k", "check", "item", "max"],
            "tuple" => &["k", "check", "items", "fixed"],
            "result" => &["k", "check", "ok", "err"],
            "option" | "recover" | "newtype" => &["k", "check", "item"],
            "ref" => &["k", "check", "name"],
            "record" => &["k", "check", "fields", "fixed"],
            "enum" => &["k", "check", "variants"],
            "extension-record" => &["k", "check", "fields", "extensions", "projected"],
            "extension-tuple" => &["k", "check", "items", "extensions", "projected"],
            "open-variant" => &["k", "check", "variants", "required"],
            _ => return Err(GenerationError::Schema),
        };
        keys(value, allowed)?;
        let node = match kind {
            "unit" => Node::Unit,
            "bool" => Node::Bool,
            "float" => {
                let bits = value["bits"].as_u64().ok_or(GenerationError::Schema)?;
                if ![32, 64].contains(&bits) {
                    return Err(GenerationError::Schema);
                }
                Node::Float { bits: bits as u8 }
            }
            "u" | "i" => {
                let bits = value["bits"].as_u64().ok_or(GenerationError::Schema)?;
                if ![8, 16, 32, 64, 128].contains(&bits) {
                    return Err(GenerationError::Schema);
                }
                Node::Integer {
                    bits: bits as u8,
                    signed: kind == "i",
                }
            }
            "text" => Node::Text {
                max: bound(value, "max")?,
            },
            "bytes" => {
                let min = bound(value, "min")?;
                let max = bound(value, "max")?;
                if min.zip(max).is_some_and(|(min, max)| min > max) {
                    return Err(GenerationError::Schema);
                }
                Node::Bytes { min, max }
            }
            "packed" => {
                let word = text(value, "word")?;
                let word = [
                    "i8",
                    "i16",
                    "u16",
                    "i32",
                    "u32",
                    "i64",
                    "u64",
                    "hash16",
                    "hash32",
                    "bool",
                    "finite-f32",
                    "finite-f64",
                ]
                .into_iter()
                .find(|candidate| *candidate == word)
                .ok_or(GenerationError::Schema)?;
                let nonzero = match value.get("nonzero") {
                    None => false,
                    Some(Value::Bool(true)) if word == "i64" => true,
                    _ => return Err(GenerationError::Schema),
                };
                let max = bound(value, "max")?;
                let width = match word {
                    "bool" | "i8" => 1,
                    "i16" | "u16" => 2,
                    "i32" | "u32" | "finite-f32" => 4,
                    "i64" | "u64" | "finite-f64" => 8,
                    "hash16" => 16,
                    _ => 32,
                };
                if max.is_some_and(|n| n > MAX_SAFE_INTEGER / width) {
                    return Err(GenerationError::Complexity);
                }
                Node::Packed { word, nonzero, max }
            }
            "list" => Node::List {
                max: bound(value, "max")?,
                item: self.parse(&value["item"], depth + 1)?,
            },
            "array" => Node::Array {
                len: bound(value, "max")?.ok_or(GenerationError::Schema)?,
                item: self.parse(&value["item"], depth + 1)?,
            },
            "tuple" | "extension-tuple" => {
                let items = value["items"].as_array().ok_or(GenerationError::Schema)?;
                if items.len() > self.remaining {
                    return Err(GenerationError::Complexity);
                }
                let items = items
                    .iter()
                    .map(|item| self.parse(item, depth + 1))
                    .collect::<Result<Vec<_>, _>>()?;
                if kind == "extension-tuple" {
                    let slots =
                        u32::try_from(items.len()).map_err(|_| GenerationError::Complexity)?;
                    Node::ExtensionTuple {
                        items,
                        extensions: self.parse_extensions(
                            &value["extensions"],
                            depth,
                            &mut BTreeSet::new(),
                            Some(slots),
                        )?,
                    }
                } else {
                    Node::Tuple(items)
                }
            }
            "result" => Node::Result {
                ok: self.parse(&value["ok"], depth + 1)?,
                err: self.parse(&value["err"], depth + 1)?,
            },
            "option" => Node::Option(self.parse(&value["item"], depth + 1)?),
            "recover" => Node::Recover(self.parse(&value["item"], depth + 1)?),
            "newtype" => Node::Alias(self.parse(&value["item"], depth + 1)?),
            "ref" => Node::Ref(
                *self
                    .names
                    .get(text(value, "name")?)
                    .ok_or(GenerationError::Schema)?,
            ),
            "record" | "enum" | "extension-record" | "open-variant" => {
                let is_open = kind == "open-variant";
                let is_enum = kind == "enum" || is_open;
                let fields = value[if is_enum { "variants" } else { "fields" }]
                    .as_array()
                    .ok_or(GenerationError::Schema)?;
                if kind == "enum" && fields.is_empty() {
                    return Err(GenerationError::Schema);
                }
                if fields.len() > self.remaining {
                    return Err(GenerationError::Complexity);
                }
                let mut seen = BTreeSet::new();
                let mut ids = BTreeSet::new();
                let mut record = Vec::new();
                let mut variants = Vec::new();
                for field in fields {
                    keys(
                        field,
                        if is_enum {
                            &["name", "id", "value"]
                        } else {
                            &["name", "value"]
                        },
                    )?;
                    let name = text(field, "name")?;
                    if !seen.insert(name) {
                        return Err(GenerationError::Schema);
                    }
                    let name = self.name(name)?;
                    let child = self.parse(&field["value"], depth + 1)?;
                    if is_enum {
                        let id = field["id"]
                            .as_u64()
                            .and_then(|id| u32::try_from(id).ok())
                            .ok_or(GenerationError::Schema)?;
                        if (is_open && !(1..=u32::MAX >> 1).contains(&id)) || !ids.insert(id) {
                            return Err(GenerationError::Schema);
                        }
                        variants.push((name, id, child));
                    } else {
                        record.push((name, child));
                    }
                }
                match kind {
                    "enum" => Node::Enum(variants),
                    "open-variant" => Node::OpenVariant {
                        variants,
                        required: match value.get("required") {
                            Some(required) => required.as_bool().ok_or(GenerationError::Schema)?,
                            None => false,
                        },
                    },
                    "extension-record" => Node::ExtensionRecord {
                        fields: record,
                        extensions: self.parse_extensions(
                            &value["extensions"],
                            depth,
                            &mut seen,
                            None,
                        )?,
                    },
                    _ => Node::Record(record),
                }
            }
            _ => return Err(GenerationError::Schema),
        };
        let id = self.nodes.len();
        let check = value
            .get("check")
            .map(|check| self.name(check.as_str().ok_or(GenerationError::Schema)?))
            .transpose()?;
        let bounds = if matches!(kind, "u" | "i" | "float")
            && (value.get("min").is_some() || value.get("max").is_some())
        {
            Some(scalar_bounds(value, kind != "float")?)
        } else {
            None
        };
        let fixed = match value.get("fixed") {
            None => false,
            Some(Value::Bool(true)) => true,
            Some(_) => return Err(GenerationError::Schema),
        };
        let projected = match value.get("projected") {
            None => false,
            Some(Value::Bool(true)) => true,
            Some(_) => return Err(GenerationError::Schema),
        };
        if check.is_some() || bounds.is_some() || fixed || projected {
            self.annotations.insert(
                id,
                Annotations {
                    check,
                    bounds,
                    fixed,
                    projected,
                },
            );
        }
        self.nodes.push(node);
        Ok(id)
    }
}

fn text<'a>(value: &'a Value, key: &str) -> Result<&'a str, GenerationError> {
    value[key].as_str().ok_or(GenerationError::Schema)
}

fn keys(value: &Value, allowed: &[&str]) -> Result<(), GenerationError> {
    if value
        .as_object()
        .ok_or(GenerationError::Schema)?
        .keys()
        .any(|key| !allowed.contains(&key.as_str()))
    {
        return Err(GenerationError::Schema);
    }
    Ok(())
}

fn bound(value: &Value, key: &str) -> Result<Option<u64>, GenerationError> {
    value
        .get(key)
        .map(|n| {
            let n = n.as_u64().ok_or(GenerationError::Schema)?;
            if n > MAX_SAFE_INTEGER {
                return Err(GenerationError::Complexity);
            }
            Ok(n)
        })
        .transpose()
}

fn identifier(name: &str) -> Result<(), GenerationError> {
    if name.is_empty()
        || !name
            .bytes()
            .enumerate()
            .all(|(i, b)| b.is_ascii_alphabetic() || b == b'_' || (i > 0 && b.is_ascii_digit()))
    {
        return Err(GenerationError::Schema);
    }
    if RESERVED.contains(&name) {
        return Err(GenerationError::Schema);
    }
    Ok(())
}

